export const AGENT_SKILL_IDS = AGENT_SKILLS.map(skill => skill.id)

/** 技能正文（含标题行）；未启用或未知 id 返回空串。 */
export function agentSkillPrompt(id: string | undefined | null): string {
  if (typeof id !== 'string' || id.trim() === '') return ''
  const skill = AGENT_SKILLS.find(item => item.id === id.trim())
  return skill === undefined ? '' : `## 教学技能：${skill.name}\n\n${skill.prompt}`
}
